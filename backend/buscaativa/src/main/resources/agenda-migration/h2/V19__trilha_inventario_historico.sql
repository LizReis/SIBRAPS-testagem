-- Somente evidência prospectiva de composição. Sem marco, backfill ou fechamento automático.
CREATE TABLE tb_movimento_inventario_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registrado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    operacao VARCHAR(12) NOT NULL,
    vinculo_anterior BIGINT,
    paciente_anterior BIGINT,
    unidade_anterior VARCHAR(80),
    vinculo_atual BIGINT,
    paciente_atual BIGINT,
    unidade_atual VARCHAR(80),
    CHECK (
        (operacao = 'INCLUSAO' AND vinculo_anterior IS NULL AND paciente_anterior IS NULL AND unidade_anterior IS NULL
            AND vinculo_atual IS NOT NULL AND paciente_atual IS NOT NULL AND unidade_atual IS NOT NULL)
        OR (operacao = 'EXCLUSAO' AND vinculo_atual IS NULL AND paciente_atual IS NULL AND unidade_atual IS NULL
            AND vinculo_anterior IS NOT NULL AND paciente_anterior IS NOT NULL AND unidade_anterior IS NOT NULL)
        OR (operacao = 'ALTERACAO' AND vinculo_anterior IS NOT NULL AND paciente_anterior IS NOT NULL AND unidade_anterior IS NOT NULL
            AND vinculo_atual IS NOT NULL AND paciente_atual IS NOT NULL AND unidade_atual IS NOT NULL)
    )
);
CREATE INDEX ix_movimento_inventario_anterior ON tb_movimento_inventario_historico(unidade_anterior,id);
CREATE INDEX ix_movimento_inventario_atual ON tb_movimento_inventario_historico(unidade_atual,id);
CREATE TRIGGER tr_inventario_historico_movimento
    AFTER INSERT, UPDATE, DELETE ON tb_vinculo_assistencial
    FOR EACH ROW CALL 'com.pet.buscaativa.migration.InventarioHistoricoTrigger';
CREATE TRIGGER tr_inventario_historico_append_only
    BEFORE UPDATE, DELETE ON tb_movimento_inventario_historico
    FOR EACH ROW CALL 'com.pet.buscaativa.migration.AuditAppendOnlyTrigger';
