-- V8: estrutura inicial do vinculo assistencial local (SEM backfill).
-- Migração exclusivamente offline pelo AgendaMigrationTool; nunca pelo startup.
-- CAPS de referencia NAO cria vinculo e nao e usado como autorizacao.
-- Os campos clinicos abaixo nao substituem os caches legados ate o plano de corte.
CREATE TABLE tb_vinculo_assistencial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_publico UUID NOT NULL,
    paciente_id BIGINT NOT NULL,
    unidade_atuacao INTEGER NOT NULL,
    usf_atuacao_id BIGINT,
    unidade_chave VARCHAR(80) NOT NULL,
    status_paciente INTEGER,
    tipo_acompanhamento INTEGER,
    count_faltas INTEGER,
    data_ultima_presenca DATE,
    classificacao_risco INTEGER,
    gatilho_visita BOOLEAN,
    indicadores_pendentes BOOLEAN,
    profissional_referencia_id BIGINT,
    version INTEGER,
    criado_em TIMESTAMP(6),
    alterado_em TIMESTAMP(6),
    criado_por VARCHAR(255),
    alterado_por VARCHAR(255),
    CONSTRAINT uk_vinculo_id_publico UNIQUE (id_publico),
    CONSTRAINT uk_vinculo_paciente_unidade UNIQUE (paciente_id, unidade_chave),
    CONSTRAINT fk_vinculo_paciente FOREIGN KEY (paciente_id) REFERENCES tb_paciente(id),
    CONSTRAINT fk_vinculo_usf FOREIGN KEY (usf_atuacao_id) REFERENCES tb_usf_referencia(id),
    CONSTRAINT fk_vinculo_profissional FOREIGN KEY (profissional_referencia_id) REFERENCES tb_usuario(id),
    CONSTRAINT ck_vinculo_tipo_unidade CHECK (
        (unidade_atuacao = 1 AND usf_atuacao_id IS NOT NULL AND unidade_chave = CONCAT('USF:', CAST(usf_atuacao_id AS VARCHAR)))
        OR (unidade_atuacao = 2 AND usf_atuacao_id IS NULL AND unidade_chave = 'CAPS_AD')
        OR (unidade_atuacao = 3 AND usf_atuacao_id IS NULL AND unidade_chave = 'CAPS_I')
        OR (unidade_atuacao = 4 AND usf_atuacao_id IS NULL AND unidade_chave = 'CAPS_II')
    )
);
CREATE INDEX ix_vinculo_paciente ON tb_vinculo_assistencial(paciente_id);

-- Envers: acrescenta somente a estrutura nova, sem inserir revisoes falsas.
CREATE TABLE tb_vinculo_assistencial_aud (
    id BIGINT NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    id_publico UUID,
    paciente_id BIGINT,
    unidade_atuacao INTEGER,
    usf_atuacao_id BIGINT,
    unidade_chave VARCHAR(80),
    status_paciente INTEGER,
    tipo_acompanhamento INTEGER,
    count_faltas INTEGER,
    data_ultima_presenca DATE,
    classificacao_risco INTEGER,
    gatilho_visita BOOLEAN,
    indicadores_pendentes BOOLEAN,
    profissional_referencia_id BIGINT,
    version INTEGER,
    criado_em TIMESTAMP(6),
    alterado_em TIMESTAMP(6),
    criado_por VARCHAR(255),
    alterado_por VARCHAR(255),
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_vinculo_aud_rev FOREIGN KEY (rev) REFERENCES revinfo(rev)
);
