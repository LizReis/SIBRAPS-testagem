-- Evidências prospectivas. Não cria marco, inventário inicial, revisão ou fechamento.
CREATE TABLE tb_movimento_evidencia_clinica (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registrado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fonte VARCHAR(64) NOT NULL CHECK (fonte IN ('TB_VINCULO_ASSISTENCIAL','TB_PACIENTE','TB_AGENDAMENTO','TB_GRUPO_TERAPEUTICO','TB_SESSAO_GRUPO','TB_SESSAO_GRUPO_PARTICIPANTE','TB_EVENTO_ESTADO_CLINICO_VINCULO')),
    operacao VARCHAR(12) NOT NULL,
    registro_anterior BIGINT,
    registro_atual BIGINT,
    assinatura_anterior VARCHAR(64),
    assinatura_atual VARCHAR(64),
    CHECK (
        (operacao='INCLUSAO' AND registro_anterior IS NULL AND assinatura_anterior IS NULL AND registro_atual IS NOT NULL AND assinatura_atual IS NOT NULL)
        OR (operacao='EXCLUSAO' AND registro_atual IS NULL AND assinatura_atual IS NULL AND registro_anterior IS NOT NULL AND assinatura_anterior IS NOT NULL)
        OR (operacao='ALTERACAO' AND registro_anterior IS NOT NULL AND assinatura_anterior IS NOT NULL AND registro_atual IS NOT NULL AND assinatura_atual IS NOT NULL)
    )
);
CREATE INDEX ix_evidencia_clinica_anterior ON tb_movimento_evidencia_clinica(fonte,registro_anterior,id);
CREATE INDEX ix_evidencia_clinica_atual ON tb_movimento_evidencia_clinica(fonte,registro_atual,id);
CREATE TABLE tb_base_evidencia_clinica (
    marco_id INTEGER PRIMARY KEY REFERENCES tb_marco_tecnico_historico(id),
    ultimo_movimento BIGINT NOT NULL CHECK (ultimo_movimento >= 0),
    total_registros BIGINT NOT NULL CHECK (total_registros >= 0)
);
CREATE TABLE tb_item_base_evidencia_clinica (
    marco_id INTEGER NOT NULL REFERENCES tb_base_evidencia_clinica(marco_id),
    fonte VARCHAR(64) NOT NULL CHECK (fonte IN ('TB_VINCULO_ASSISTENCIAL','TB_PACIENTE','TB_AGENDAMENTO','TB_GRUPO_TERAPEUTICO','TB_SESSAO_GRUPO','TB_SESSAO_GRUPO_PARTICIPANTE','TB_EVENTO_ESTADO_CLINICO_VINCULO')),
    registro BIGINT NOT NULL,
    assinatura VARCHAR(64) NOT NULL,
    PRIMARY KEY (marco_id,fonte,registro)
);
