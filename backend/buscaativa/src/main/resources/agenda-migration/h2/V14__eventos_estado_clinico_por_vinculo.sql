-- Eventos contemporâneos. Sem backfill ou criação de revisões.
ALTER TABLE tb_vinculo_assistencial
    ADD CONSTRAINT uk_vinculo_evento_unidade UNIQUE (id, unidade_chave);

CREATE TABLE tb_evento_estado_clinico_vinculo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vinculo_id BIGINT NOT NULL,
    unidade_chave VARCHAR(80) NOT NULL,
    ator_id BIGINT NOT NULL,
    ocorrido_em TIMESTAMP(6) NOT NULL,
    natureza VARCHAR(20) NOT NULL,
    status_anterior INTEGER,
    status_resultante INTEGER NOT NULL,
    motivo VARCHAR(2000),
    descricao VARCHAR(2000),
    CONSTRAINT fk_evento_estado_vinculo_local FOREIGN KEY (vinculo_id, unidade_chave)
        REFERENCES tb_vinculo_assistencial(id, unidade_chave),
    CONSTRAINT fk_evento_estado_ator FOREIGN KEY (ator_id) REFERENCES tb_usuario(id),
    CONSTRAINT ck_evento_estado_clinico CHECK (
        (status_anterior IS NULL OR status_anterior BETWEEN 1 AND 7)
        AND (
            (natureza = 'INICIALIZACAO' AND status_anterior IS NULL
                AND status_resultante = 1 AND motivo IS NULL AND descricao IS NULL)
            OR (natureza = 'ENCERRAMENTO' AND status_resultante BETWEEN 2 AND 7
                AND (status_anterior IS NULL OR status_anterior <> status_resultante)
                AND motivo IS NOT NULL
                AND motivo IN ('ALTA_TERAPEUTICA', 'TRANSFERENCIA_OUTRA_UNIDADE', 'ABANDONO_TRATAMENTO', 'OBITO', 'OUTRO')
                AND (motivo <> 'OUTRO' OR (descricao IS NOT NULL AND LENGTH(TRIM(descricao)) > 0)))
            OR (natureza = 'REATIVACAO' AND status_anterior IS NOT NULL AND status_anterior BETWEEN 2 AND 7
                AND status_resultante = 1 AND motivo IS NOT NULL AND LENGTH(TRIM(motivo)) > 0
                AND descricao IS NULL)
        )
    )
);

CREATE INDEX ix_evento_estado_vinculo ON tb_evento_estado_clinico_vinculo(vinculo_id, id);

CREATE TRIGGER tr_evento_estado_clinico_append_only
    BEFORE UPDATE, DELETE ON tb_evento_estado_clinico_vinculo
    FOR EACH ROW CALL 'com.pet.buscaativa.migration.AuditAppendOnlyTrigger';

CREATE TABLE tb_evento_estado_clinico_vinculo_aud (
    id BIGINT NOT NULL,
    rev INTEGER NOT NULL,
    revtype SMALLINT,
    vinculo_id BIGINT,
    unidade_chave VARCHAR(80),
    ator_id BIGINT,
    ocorrido_em TIMESTAMP(6),
    natureza VARCHAR(20),
    status_anterior INTEGER,
    status_resultante INTEGER,
    motivo VARCHAR(2000),
    descricao VARCHAR(2000),
    PRIMARY KEY (id, rev),
    CONSTRAINT fk_evento_estado_rev FOREIGN KEY (rev) REFERENCES revinfo(rev)
);
CREATE INDEX ix_evento_estado_aud_vinculo ON tb_evento_estado_clinico_vinculo_aud(vinculo_id, rev);
